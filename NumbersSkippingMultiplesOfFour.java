//12 	Print numbers from 1 to 100 skipping multiples of 4.

public class NumbersSkippingMultiplesOfFour{ 

  public static void main(String[]args){
  
  for( int number =1; number <= 100; number++){ 
  
    if(number % 4 != 0) { 
    
      System.out.println(number);
    
    
    }
    
  
  }
  
  
  
  }



}



