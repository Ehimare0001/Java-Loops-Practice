//20. Print the multiplication table of 12.

public class TwelveMultiplicationTable{ 

  public static void main(String[]args) {
  
  int number = 1;
  
  while(number <= 12) {
    int Multiplication = 12 * number;
  System.out.println( 12 + " x " + number + " = " + Multiplication);
    number++;
  
  
  }
    
  
  }

}
